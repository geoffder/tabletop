import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { Country } from '@tabletop/web-of-power'
import { ADVISOR_RINGS } from './advisorRings.js'
import { computeRing, mostAdvisors } from './advisorSpots.js'

const round = (spots: { x: number; y: number }[]) =>
    spots.map(({ x, y }) => ({ x: Math.round(x * 100) / 100, y: Math.round(y * 100) / 100 }))

const fresh = () =>
    Object.fromEntries(
        Object.values(Country).map((country) => [
            country,
            Array.from({ length: mostAdvisors(country) }, (_, index) =>
                round(computeRing(country, index + 1))
            )
        ])
    )

describe('advisor spots', () => {
    it('keeps the worked-out table in step with advisorRing', () => {
        const table = fresh()
        // eslint-disable-next-line turbo/no-undeclared-env-vars -- a hand-run switch, not a build input
        if (process.env.UPDATE) {
            const body = JSON.stringify(table)
            writeFileSync(
                join(dirname(fileURLToPath(import.meta.url)), 'advisorRings.ts'),
                `// Generated by advisorSpots.spec.ts (UPDATE=1): each country's advisor spots for 1 to\n// its most advisors, from advisorRing. Do not edit by hand.\nexport const ADVISOR_RINGS: Record<string, { x: number; y: number }[][]> = ${body}\n`
            )
            return
        }
        expect(ADVISOR_RINGS).toEqual(table)
    })
})
